#!/usr/bin/env node
/* ============================================================
   build-spm-course.js — generates the Year 12 Specialist course hub
   (course home + one page per topic) from a single data file.

     node tools/build-spm-course.js          # write the pages
     node tools/build-spm-course.js --check  # exit 1 if any page is stale

   Source of truth: year12-specialist/2027/course.json. Edit dates,
   sections, links and milestones there, never in the generated HTML.
   Week dates come from each term's Week 1 Monday, so moving a term or
   a SAC is a one-line change. Plain Node, no packages.
   ============================================================ */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DATA = path.join(ROOT, "year12-specialist", "2027", "course.json");
const CHECK = process.argv.includes("--check");

const course = JSON.parse(fs.readFileSync(DATA, "utf8"));
const OUT = path.join(ROOT, course.out);

/* ---------- helpers ---------- */
const esc = s => String(s)
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const MON = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];
const parse = iso => { const [y, m, d] = iso.split("-").map(Number); return new Date(Date.UTC(y, m - 1, d)); };
const iso = dt => dt.toISOString().slice(0, 10);
const addDays = (dt, n) => new Date(dt.getTime() + n * 86400000);
const dayMon = dt => dt.getUTCDate() + " " + MON[dt.getUTCMonth()];
function range(a, b) {
  return a.getUTCMonth() === b.getUTCMonth()
    ? a.getUTCDate() + "–" + dayMon(b)
    : dayMon(a) + "–" + dayMon(b);
}

const termOf = n => {
  const t = course.terms.find(x => x.n === n);
  if (!t) throw new Error("No term " + n + " in course.json");
  return t;
};

function weekInfo(t, w) {
  const term = termOf(t);
  if (w < 1 || w > term.weeks) throw new Error("Term " + t + " has no Week " + w);
  const mon = addDays(parse(term.monday), 7 * (w - 1));
  let fri = addDays(mon, 4);
  if (term.lastDay && parse(term.lastDay) < fri) fri = parse(term.lastDay);
  const ab = course.abCycle === "restart" ? (w % 2 ? "A" : "B") : "";
  const events = course.events
    .filter(e => { const d = parse(e.date); return d >= mon && d <= addDays(mon, 6); })
    .map(e => e.label);
  return { mon, fri, ab, events, end: addDays(fri, 1) };
}

function weeksLabel(weeks) {
  const a = weeks[0], b = weeks[weeks.length - 1];
  if (a.t === b.t) return "Term " + a.t + (a.w === b.w ? " Week " + a.w : " Weeks " + a.w + "–" + b.w);
  return "Term " + a.t + " Wk " + a.w + " – Term " + b.t + " Wk " + b.w;
}

/* ---------- page shell ---------- */
const head = title => `<!DOCTYPE html>
<html lang="en">
<head>
<!-- Generated by tools/build-spm-course.js from course.json. Edit the data file, not this page. -->
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(title)}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Bitter:wght@500;700;800&family=Source+Sans+3:ital,wght@0,400;0,600;0,700;1,400&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../../assets/css/tokens.css">
<link rel="stylesheet" href="../../assets/css/hub.css">
<link rel="stylesheet" href="../../assets/css/sitenav.css">
<script src="../../assets/js/sitenav.js" defer></script>
<link rel="icon" href="../../assets/icons/favicon.svg" type="image/svg+xml">
<link rel="icon" href="../../assets/icons/favicon.ico" sizes="32x32">
<link rel="apple-touch-icon" href="../../assets/icons/apple-touch-icon.png">
<link rel="manifest" href="../../site.webmanifest">
<meta name="theme-color" content="#24576f">
</head>
<body class="hub-page ${esc(course.theme)}">
`;

const foot = text => `
<footer>${esc(text)}</footer>

<script src="../../assets/js/hub.js" defer></script>
</body>
</html>
`;

/* ---------- course home ---------- */
function milestoneHTML(m) {
  let detail = m.detail || "";
  if (m.tbc && !/TBC/.test(detail)) detail += (detail ? " · " : "") + "TBC";
  const cd = m.countdown && m.date ? ` · <span class="countdown" data-to="${m.date}"></span>` : "";
  const dateAttr = m.date ? ` data-date="${m.date}"` : "";
  return `    <div class="mile ${esc(m.cls || "")}"${dateAttr}><b>${esc(m.label)}</b><span>${esc(detail)}${cd}</span></div>`;
}

function homePage() {
  const topics = course.topics.map((tp, i) => {
    const meta = [tp.chapters, tp.weeks.length + (tp.weeks.length === 1 ? " week" : " weeks")]
      .concat(tp.assessed ? [tp.assessed] : []).join(" · ");
    return `    <a class="topic" href="${tp.slug}.html">
      <span class="tp-eyebrow">Topic ${i + 1} · Unit ${tp.unit} · ${esc(weeksLabel(tp.weeks))}</span>
      <span class="tp-title">${esc(tp.title)}</span>
      <span class="tp-meta">${esc(meta)}</span>
    </a>`;
  }).join("\n");

  return head(course.title + " — " + course.year + " Course Home") + `
<header class="hub-head">
  <div class="head-row">
    <div>
      <h1>${esc(course.title)} — ${course.year}</h1>
      <p>${esc(course.subtitle)}</p>
    </div>
    <a href="${esc(course.back.href)}" class="backlink">${esc(course.back.label)}</a>
  </div>
  <div class="timeline" id="timeline">
${course.milestones.map(milestoneHTML).join("\n")}
  </div>
</header>

<main>
  <h2>Topics</h2>
  <p class="legend">Choose a topic for its weeks, sections, slides and problem sets. Dates marked TBC are planned windows and may move.</p>
  <nav class="topic-grid" aria-label="Topics">
${topics}
  </nav>
</main>
` + foot(course.footer);
}

/* ---------- topic pages ---------- */
function weekHTML(wk) {
  const info = weekInfo(wk.t, wk.w);
  const dates = [range(info.mon, info.fri)].concat(info.events).join(" · ");
  const items = (wk.items || []).map(([code, text]) =>
    `          <li><b>${esc(code)}</b> ${esc(text)}</li>`).join("\n");
  const links = wk.links && wk.links.length
    ? `\n        <div class="links">\n${wk.links.map(([href, label]) =>
        `          <a href="${esc(href)}">${esc(label)}</a>`).join("\n")}\n        </div>`
    : "";
  return `      <div class="week" data-start="${iso(info.mon)}" data-end="${iso(info.end)}">
        <div class="wk-head"><h3>Term ${wk.t} · Week ${wk.w}${info.ab}</h3><span class="dates">${esc(dates)}</span><span class="aos ${esc(wk.tagCls || "aosC")}">${esc(wk.tag)}</span></div>
        <ul class="periods">
${items}
        </ul>${links}
      </div>`;
}

function topicPage(tp, i) {
  const prev = course.topics[i - 1], next = course.topics[i + 1];
  const pager = [
    prev ? `    <a class="ch-open" href="${prev.slug}.html">&larr; Topic ${i}: ${esc(prev.title)}</a>`
         : `    <a class="ch-open" href="./">&larr; Course home</a>`,
    next ? `    <a class="ch-open" href="${next.slug}.html">Topic ${i + 2}: ${esc(next.title)} &rarr;</a>`
         : `    <a class="ch-open" href="./">Course home &rarr;</a>`
  ].join("\n");
  const sub = ["Specialist " + course.year, "Unit " + tp.unit, weeksLabel(tp.weeks), tp.chapters].join(" · ");

  return head(`Topic ${i + 1} · ${tp.title} | Specialist Maths ${course.year}`) + `
<header class="hub-head">
  <div class="head-row">
    <div>
      <h1>Topic ${i + 1} — ${esc(tp.title)}</h1>
      <p>${esc(sub)}</p>
    </div>
    <a href="./" class="backlink">&#8592; All topics</a>
  </div>
</header>

<main class="topic-main">
  <section class="chapter">
    <div class="ch-head">
      <div>
        <h2>Week by week</h2>
        <p class="ch-meta">${esc(tp.note || "Sections are listed in teaching order; slides and problem sets appear under each week as they are published.")}</p>
      </div>
    </div>
    <div class="grid" id="weeks">
${tp.weeks.map(weekHTML).join("\n")}
    </div>
  </section>

  <nav class="topic-pager" aria-label="Topics">
${pager}
  </nav>
</main>
` + foot(`Topic ${i + 1} · ${tp.title} · ${course.footer}`);
}

/* ---------- write / check ---------- */
const pages = [["index.html", homePage()]]
  .concat(course.topics.map((tp, i) => [tp.slug + ".html", topicPage(tp, i)]));

let stale = 0;
for (const [name, html] of pages) {
  const file = path.join(OUT, name);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === html) continue;
  if (CHECK) { console.log("stale: " + path.relative(ROOT, file)); stale++; }
  else { fs.writeFileSync(file, html); console.log("wrote " + path.relative(ROOT, file)); }
}
if (CHECK) {
  if (stale) { console.log(stale + " page(s) out of date — run node tools/build-spm-course.js"); process.exit(1); }
  console.log("Specialist course pages are up to date.");
}
