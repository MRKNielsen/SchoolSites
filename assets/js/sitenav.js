/* ============================================================
   sitenav.js — SITE-WIDE NAVIGATION DRAWER
   Load once per page, after tokens.css + sitenav.css:

     <script src="../../assets/js/sitenav.js" defer></script>

   That single tag is the whole per-page cost: this script works out
   where the repo root is from its own src, then loads
   assets/js/sitemap.js (generated by tools/build-sitemap.js) and
   builds the tree. Adding a page means re-running the generator, not
   editing any markup.

   Opening: click the edge handle, or press N. Escape closes.
   While the drawer is open the keyboard is captured, so a deck sitting
   underneath does not also advance a slide — see the capture-phase
   listener at the bottom.

   Deliberately not root-relative: the site is served from
   /SchoolSites/ on GitHub Pages, so every href is resolved against the
   computed root prefix instead of "/".
   ============================================================ */
(function () {
  "use strict";

  /* ---------- Where is the repo root? -------------------------
     document.currentScript is still valid for a deferred classic
     script at parse time, and gives the exact relative depth the page
     author wrote — no guessing from location.pathname, which would
     break under the /SchoolSites/ project-pages prefix. */
  var self = document.currentScript;
  var ROOT = self ? self.src.replace(/assets\/js\/sitenav\.js(\?.*)?$/, "") : "";

  /* Current page, normalised to a repo-root-relative path so it can be
     compared against sitemap hrefs. */
  var HERE = (function () {
    var here = location.href.split(/[?#]/)[0];
    var root = new URL(ROOT || ".", location.href).href;
    var rel = here.indexOf(root) === 0 ? here.slice(root.length) : "";
    if (rel === "") rel = "index.html";              /* served as a bare / */
    return decodeURIComponent(rel.replace(/\/$/, "/index.html"));
  })();

  var open = false, built = false, panel, tree, search, handle, wrap;
  var links = [], sections = [];

  /* ---------- Tiny DOM helper --------------------------------- */
  function el(tag, cls, text) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;
    return n;
  }

  /* ---------- Build ------------------------------------------- */
  function buildHandle() {
    handle = el("button", "sn-handle");
    handle.type = "button";
    handle.setAttribute("aria-label", "Open site navigation");
    handle.setAttribute("aria-expanded", "false");
    handle.appendChild(el("i"));
    handle.appendChild(el("i"));
    handle.appendChild(el("i"));
    handle.addEventListener("click", toggle);
    document.body.appendChild(handle);
  }

  function linkNode(node, extraClass) {
    var a = el("a", "sn-link" + (extraClass ? " " + extraClass : ""));
    a.href = ROOT + node.h;
    a.appendChild(el("span", "sn-text", node.t));
    if (node.p) a.appendChild(el("span", "sn-note", "PDF"));
    if (node.h === HERE) {
      a.setAttribute("aria-current", "page");
      a.dataset.current = "1";
    }
    a.dataset.find = (node.t + " " + node.h).toLowerCase();
    links.push(a);
    return a;
  }

  /* A branch renders as <details>; its own landing page (if it has one)
     becomes the first child link rather than making the summary a link,
     because a summary that is also a link fights the disclosure. */
  function branch(node, depth) {
    var d = el("details", "sn-sec");
    var s = el("summary");
    s.appendChild(el("span", "sn-caret"));
    if (node.k) { var dot = el("span", "sn-dot"); dot.classList.add("sn-t-" + node.k); s.appendChild(dot); }
    s.appendChild(el("span", "sn-label", node.t));
    if (node.s) s.appendChild(el("span", "sn-sub", node.s));
    d.appendChild(s);

    var kids = el("div", "sn-kids");
    if (node.h) kids.appendChild(linkNode(node, "sn-self"));
    (node.c || []).forEach(function (child) { kids.appendChild(render(child, depth + 1)); });
    d.appendChild(kids);

    d.dataset.depth = depth;
    sections.push(d);
    return d;
  }

  function render(node, depth) {
    if (node.g) {                                   /* group heading */
      var frag = document.createDocumentFragment();
      frag.appendChild(el("p", "sn-group", node.t));
      (node.c || []).forEach(function (c) { frag.appendChild(render(c, depth)); });
      return frag;
    }
    if (node.c && node.c.length) return branch(node, depth);
    if (node.h) return linkNode(node);
    return document.createDocumentFragment();
  }

  function build(map) {
    wrap = el("div");
    wrap.id = "sitenav";
    wrap.hidden = false;
    wrap.setAttribute("role", "dialog");
    wrap.setAttribute("aria-modal", "false");
    wrap.setAttribute("aria-label", "Site navigation");

    panel = el("div", "sn-panel");

    /* Header */
    var head = el("div", "sn-head");
    var brand = el("div", "sn-brand");
    brand.appendChild(el("span", "sn-mark", "KNI"));
    brand.appendChild(el("p", "sn-title", "Class Materials"));
    var close = el("button", "sn-close", "×");
    close.type = "button";
    close.setAttribute("aria-label", "Close site navigation");
    close.addEventListener("click", hide);
    brand.appendChild(close);
    head.appendChild(brand);

    search = el("input", "sn-search");
    search.type = "search";
    search.placeholder = "Filter pages…";
    search.setAttribute("aria-label", "Filter pages");
    search.autocomplete = "off";
    search.addEventListener("input", filter);
    head.appendChild(search);
    panel.appendChild(head);

    /* Tree */
    tree = el("nav", "sn-tree");
    tree.setAttribute("aria-label", "All pages");
    (map.tree || []).forEach(function (n) { tree.appendChild(render(n, 0)); });
    panel.appendChild(tree);

    /* Footer */
    var foot = el("div", "sn-foot");
    var hint = el("span");
    hint.appendChild(document.createTextNode("Press "));
    hint.appendChild(el("kbd", null, "N"));
    hint.appendChild(document.createTextNode(" anywhere"));
    foot.appendChild(hint);
    foot.appendChild(el("span", null, map.generated || ""));
    panel.appendChild(foot);

    wrap.appendChild(panel);
    wrap.addEventListener("click", function (e) { if (e.target === wrap) hide(); });
    document.body.appendChild(wrap);

    revealCurrent();
    built = true;
  }

  /* Open every ancestor of the current page, and only those — so the
     drawer opens showing where you are, not a wall of every page on the
     site. Falls back to the top level when there is nothing to expand
     (the home page, or a page not in the map). */
  function openTopLevel() {
    sections.forEach(function (s) { s.open = s.dataset.depth === "0"; });
  }

  function revealCurrent() {
    var cur = tree.querySelector('[data-current="1"]');
    if (!cur) { openTopLevel(); return; }

    var p = cur.parentNode, found = 0;
    while (p && p !== tree) {
      if (p.tagName === "DETAILS") { p.open = true; found++; }
      p = p.parentNode;
    }
    if (!found) { openTopLevel(); return; }         /* current page is top level */

    requestAnimationFrame(function () {
      if (cur.scrollIntoView) cur.scrollIntoView({ block: "center" });
    });
  }

  /* ---------- Filter ------------------------------------------ */
  function filter() {
    var q = search.value.trim().toLowerCase();
    tree.querySelectorAll(".sn-empty").forEach(function (n) { n.remove(); });

    if (!q) {
      links.forEach(function (a) { a.classList.remove("sn-hidden"); });
      sections.forEach(function (s) { s.classList.remove("sn-hidden"); s.open = false; });
      tree.querySelectorAll(".sn-group").forEach(function (g) { g.classList.remove("sn-hidden"); });
      revealCurrent();
      return;
    }

    var hits = 0;
    links.forEach(function (a) {
      var hit = a.dataset.find.indexOf(q) !== -1;
      a.classList.toggle("sn-hidden", !hit);
      if (hit) hits++;
    });
    /* A section survives if anything inside it did; a group heading
       survives if a link after it did. */
    sections.forEach(function (s) {
      var any = s.querySelector(".sn-link:not(.sn-hidden)");
      s.classList.toggle("sn-hidden", !any);
      s.open = !!any;
    });
    tree.querySelectorAll(".sn-group").forEach(function (g) {
      var any = false, n = g.nextElementSibling;
      while (n && !n.classList.contains("sn-group")) {
        if (n.classList.contains("sn-link") ? !n.classList.contains("sn-hidden")
                                            : n.querySelector(".sn-link:not(.sn-hidden)")) { any = true; break; }
        n = n.nextElementSibling;
      }
      g.classList.toggle("sn-hidden", !any);
    });

    if (!hits) tree.appendChild(el("p", "sn-empty", "Nothing matches “" + search.value.trim() + "”."));
  }

  /* ---------- Open / close ------------------------------------ */
  function show() {
    if (!built) return;
    open = true;
    document.body.classList.add("sn-open");
    handle.setAttribute("aria-expanded", "true");
    setTimeout(function () { search.focus(); }, 60);
  }
  function hide() {
    if (!built) return;
    open = false;
    document.body.classList.remove("sn-open");
    handle.setAttribute("aria-expanded", "false");
    handle.focus({ preventScroll: true });
  }
  function toggle() { open ? hide() : show(); }

  /* ---------- Keyboard ----------------------------------------
     Capture phase so this runs before deck.js's document-level
     handler regardless of script order: while the drawer is open the
     event is stopped there and the deck underneath stays put. */
  function typing(t) {
    if (!t || typeof t.matches !== "function") return false;   /* e.g. document */
    return t.matches("input, textarea, select") || t.isContentEditable;
  }

  document.addEventListener("keydown", function (e) {
    if (e.ctrlKey || e.metaKey || e.altKey) return;

    if (open) {
      if (e.key === "Escape") {
        if (search.value) { search.value = ""; filter(); }
        else hide();
        e.preventDefault(); e.stopPropagation();
        return;
      }
      /* Let the browser handle typing and tabbing; swallow everything
         else so the page underneath doesn't act on it. */
      if (e.key === "Tab") return;
      if (typing(e.target)) {
        if (e.key === "ArrowDown" || e.key === "Enter") {
          var first = tree.querySelector(".sn-link:not(.sn-hidden)");
          if (first) { first.focus(); e.preventDefault(); }
        }
        e.stopPropagation();
        return;
      }
      if (e.key === "ArrowDown" || e.key === "ArrowUp") {
        var vis = links.filter(function (a) {
          return !a.classList.contains("sn-hidden") && a.offsetParent !== null;
        });
        var i = vis.indexOf(document.activeElement);
        var n = e.key === "ArrowDown" ? i + 1 : i - 1;
        if (n >= 0 && n < vis.length) vis[n].focus();
        e.preventDefault();
      }
      e.stopPropagation();
      return;
    }

    if ((e.key === "n" || e.key === "N") && !typing(e.target)) {
      /* Don't fight a deck's own slide-jump overlay. */
      if (document.querySelector(".slidemenu:not([hidden])")) return;
      show();
      e.preventDefault(); e.stopPropagation();
    }
  }, true);

  /* ---------- Boot -------------------------------------------- */
  function start() {
    buildHandle();
    if (window.SITEMAP) { build(window.SITEMAP); return; }
    var s = document.createElement("script");
    s.src = ROOT + "assets/js/sitemap.js";
    s.onload = function () {
      if (window.SITEMAP) build(window.SITEMAP);
      else handle.remove();
    };
    s.onerror = function () { handle.remove(); };   /* no map, no handle */
    document.head.appendChild(s);
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start);
  else start();
})();
