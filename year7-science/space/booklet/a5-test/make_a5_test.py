def check_text(master_body, out_text):
    """Every word of the master's Section 1 prose survives. Markup is not
    prose: environment names, TikZ options and colour names are ignored.
    The one deliberate removal is each set's "Check your understanding ...
    N marks" line: the title now prints in the You do box's tab (the box's
    default title) and marks are no longer shown."""
    def words(t):
        t = re.sub(r"%.*", "", t)
        t = re.sub(r"\\textbf\{\\headingfont Check your understanding\}\\hfill"
                   r"\\textcolor\{DarkGrey\}\{\\itshape \d+ marks\}", " ", t)
        t = re.sub(r"\\(begin|end)\{[^}]*\}", " ", t)
        t = re.sub(r"\[[^\]]*\]", " ", t)          # tikz / environment options
        t = re.sub(r"\\[a-zA-Z]+\*?", " ", t)
        return re.findall(r"[A-Za-z][A-Za-z'-]+", t)
    from collections import Counter
    a, b = Counter(words(master_body)), Counter(words(out_text))
