def slug(w):
    return re.sub(r"[^a-z0-9]+", "-", w.lower()).strip("-")


def body_of_section1(master):
    a = master.index(r"\section{Earth, Moon and Sun --- Scale and Structure}\label{sec:1}")
    b = master.index(r"\section{Day, Night and Seasons}\label{sec:2}")
    body = master[a:b]
    # drop the trailing page breaks / rule comments before section 2
    body = re.sub(r"(\\newpage\s*%\s*=+\s*)+$", "", body.rstrip())
    return body


def transform(body):
    vc = re.search(r"\\vc\{Science Understanding\}\{([^}]*)\}", body).group(1)
    body = body.replace(r"\section{Earth, Moon and Sun --- Scale and Structure}\label{sec:1}", "", 1)
    body = re.sub(r"\\vc\{Science Understanding\}\{[^}]*\}\n", "", body, count=1)
    body = re.sub(r"%\s*=+\n", "", body)
    body = body.replace(r"\newpage", "")

    # Check your understanding: You do box, title in the tab, no marks line.
    body = re.sub(r"\\begin\{yr7box\}\s*\\textbf\{\\headingfont Check your understanding\}\\hfill\\textcolor\{DarkGrey\}\{\\itshape \d+ marks\}",
                  r"\\begin{youdobox}", body)
    body = body.replace(r"\end{yr7box}", r"\end{youdobox}")
    body = body.replace(r"\begin{workedex}", r"\begin{idobox}").replace(r"\end{workedex}", r"\end{idobox}")
    body = body.replace(r"\begin{scaffold}", r"\begin{wedobox}").replace(r"\end{scaffold}", r"\end{wedobox}")
    body = body.replace(r"\begin{infobox}", r"\begin{keybox}").replace(r"\end{infobox}", r"\end{keybox}")
    body = body.replace(r"\begin{fnbox}", r"\begin{countrybox}").replace(r"\end{fnbox}", r"\end{countrybox}")
    # Year 8: the first box of the pair starts a new page, both are Above level.
    body = body.replace(r"\begin{yr8box}\label{y8:1.moon}", "\\clearpage\n\\begin{abovebox}\\label{y8:1.moon}")
    body = body.replace(r"\begin{yr8box}", r"\begin{abovebox}").replace(r"\end{yr8box}", r"\end{abovebox}")

    # Answer space. Inside a You do set the boxes start small and fill.py
    # shares out the rest of the page; elsewhere a written answer is >= 5 cm.
    # A question whose task is a calculation gets a plain working box.
    out, in_youdo, calc = [], False, False
    for line in body.split("\n"):
        if r"\begin{youdobox}" in line:
            in_youdo = True
        if r"\end{youdobox}" in line:
            in_youdo = False
        if r"\question{" in line:
            calc = bool(re.search(r"\b(Calculate|calculate)\b", line))
        m = re.match(r"(\s*)\\anslines\{(\d+)\}\s*$", line)
        if m:
            n = int(m.group(2))
            h = "1.6cm" if in_youdo else "5.0cm"
            line = m.group(1) + (r"\workbox{%s}" if calc else r"\answerbox{%s}") % h
        out.append(line)
    body = "\n".join(out)
    # The Your turn box is a calculation too.
    body = body.replace(r"\answerbox{4cm}", r"\workbox{4cm}")

    # Labelling diagrams in ink: separators black, bands patterned, and a
    # touch smaller so the label rail fits the A5 measure.
    body = body.replace("band/.style={draw=white, line width=1.1pt},",
                        "band/.style={draw=Ink, line width=0.7pt},")
    body = body.replace(r"\begin{tikzpicture}[" + "\n    band/",
                        r"\begin{tikzpicture}[scale=0.84, every node/.style={transform shape}," + "\n    band/")
    for old, new in [("fill=Space!30", "ink light"), ("fill=Space!55", "ink mid"),
                     ("fill=Gold!45", "ink dots"), ("fill=Gold!90", "ink solid"),
                     ("fill=Gold!15", "ink white"), ("fill=Coral!45", "ink dots"),
                     ("fill=GoldDark!75", "ink mid"), ("fill=Gold!40", "ink light"),
                     ("fill=Gold!70", "ink rows"), ("fill=Coral!90", "ink solid")]:
        body = body.replace(old, new)

    # "~" before a number means "about" in the master, but LaTeX prints it as
    # an invisible space. Show the tilde (bug reported for the master too).
    body = re.sub(r"~(?=\d)", r"\\textasciitilde ", body)

    # Data table: a little smaller on A5.
    body = body.replace("\\begin{center}\n\\begin{tabular}{lrrr}", "\\begin{center}\\small\n\\begin{tabular}{lrrr}", 1)

    # Glossary labels on the first use of every \vocab word.
    words, seen = [], set()

    def lab(m):
        w = m.group(1)
        key = slug(w)
        if key in seen:
            return m.group(0)
        seen.add(key)
        words.append(w)
        return m.group(0) + r"\label{voc:%s}" % key

    body = re.sub(r"\\vocab\{([^}]*)\}", lab, body)
    return vc, body, words


