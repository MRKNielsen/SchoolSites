                     ("{\\headingfont Lesson Booklet 1 \\textbullet\\ Lessons 1--7 \\textbullet\\ Year 7}", "{\\headingfont Lesson Booklet \\textbullet\\ Lessons 1--7 \\textbullet\\ Year 7}"),
