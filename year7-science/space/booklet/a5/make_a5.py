def check_words(raw_all, doc):
    def words(t):
        t = re.sub(r"%.*", "", t)
        t = re.sub(r"\\textbf\{\\headingfont Check your understanding\}\\hfill"
                   r"\\textcolor\{DarkGrey\}\{\\itshape \d+ marks?\}", " ", t)
        t = re.sub(r"\\(begin|end)\{[^}]*\}", " ", t)
        t = re.sub(r"\[[^\]]*\]", " ", t)
        t = re.sub(r"\\[a-zA-Z]+\*?", " ", t)
        return re.findall(r"[A-Za-z][A-Za-z'-]+", t)
    from collections import Counter
    ignore = {'lll', 'll', 'rll', 'lllp', 'red', 'blue', 'green', 'orange', 'yellow', 'brown', 'purple', 'violet', 'teal', 'cyan', 'magenta', 'figure', 'screenshot'}
    a, b = Counter(words("".join(raw_all))), Counter(words(doc))
    lost = {k: v for k, v in (a - b).items() if k.lower() not in ignore}
    if lost:
        sys.exit("text lost: %s" % lost)


def at_level_front(doc):
    """One at-level book: no above-level rows, Lessons 8-10 point to Advanced Space."""
